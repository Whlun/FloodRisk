import type { FormInstance } from 'antd';
import type { Level1Factor, RiskIndicatorRow } from './types';

/** 与导则种子一致的一级因子编码前缀 */
export const LEVEL1_INDICATOR_CODE_PREFIX: Record<Level1Factor, string> = {
  HAZARD: 'HZ',
  FORMATION: 'FM',
  BEARING: 'BR',
  PREVENTION: 'PR',
};

const AUTO_CODE_PATTERN = /^(HZ|FM|BR|PR)_U(\d+)$/i;

/** 是否为系统自动生成的用户指标编码 */
export function isAutoGeneratedIndicatorCode(code: string | undefined): boolean {
  if (!code?.trim()) return false;
  return AUTO_CODE_PATTERN.test(code.trim());
}

/** 生成下一可用指标编码（用户自建：{一级前缀}_U{三位序号}） */
export function generateNextIndicatorCode(
  indicators: Pick<RiskIndicatorRow, 'code'>[],
  level1: Level1Factor,
  excludeCode?: string,
): string {
  const prefix = LEVEL1_INDICATOR_CODE_PREFIX[level1];
  const pattern = new RegExp(`^${prefix}_U(\\d+)$`, 'i');
  const exclude = excludeCode?.trim().toUpperCase();
  let max = 0;
  for (const row of indicators) {
    const c = row.code.trim();
    if (exclude && c.toUpperCase() === exclude) continue;
    const m = c.match(pattern);
    if (m) max = Math.max(max, parseInt(m[1], 10));
  }
  return `${prefix}_U${String(max + 1).padStart(3, '0')}`;
}

/** 写入表单并同步普查字段键（新建向导 / 打开新增时） */
export function assignAutoIndicatorCodeToForm(
  form: FormInstance,
  indicators: Pick<RiskIndicatorRow, 'code'>[],
  level1: Level1Factor,
  options?: { excludeCode?: string; syncFieldKey?: boolean },
): string {
  const code = generateNextIndicatorCode(indicators, level1, options?.excludeCode);
  form.setFieldValue('code', code);
  if (options?.syncFieldKey !== false) {
    const survey = (form.getFieldValue('survey') as RiskIndicatorRow['survey'] | undefined) ?? {};
    const fieldKey = String(survey.fieldKey ?? '').trim();
    const prevCode = String(form.getFieldValue('_autoCodePrev') ?? '').trim();
    if (!fieldKey || fieldKey === prevCode) {
      form.setFieldsValue({
        survey: { ...survey, fieldKey: code },
      });
    }
  }
  form.setFieldValue('_autoCodePrev', code);
  return code;
}
