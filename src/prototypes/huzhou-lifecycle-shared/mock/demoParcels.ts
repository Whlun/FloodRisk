/** 湖州市五区县 · 预警演示地块挂接（parcel.region = 地图 hzDistrictName 来源） */
export const HZ_ALERT_PARCELS_BY_DISTRICT = {
  吴兴区: ['qsmzq-guid-alert-004', 'qsmzq-guid-alert-010', 'qsmzq-guid-alert-011'],
  南浔区: ['qsmzq-guid-alert-006', 'qsmzq-guid-alert-009'],
  德清县: ['qsmzq-guid-alert-008', 'qsmzq-guid-alert-013'],
  长兴县: ['qsmzq-guid-alert-005', 'qsmzq-guid-alert-007'],
  安吉县: ['qsmzq-guid-alert-012', 'qsmzq-guid-alert-014'],
} as const satisfies Record<string, readonly string[]>;

export type HzDistrictName = keyof typeof HZ_ALERT_PARCELS_BY_DISTRICT;

/** 台账地块所属区县（与顶栏 / GeoJSON hzDistrictName 一致） */
export function getParcelDistrictName(parcelId: string): string | undefined {
  const region = getParcelById(parcelId)?.region?.trim();
  return region || undefined;
}

/** 地块是否属于指定区县 */
export function parcelMatchesDistrict(
  parcelId: string,
  districtName: string | null | undefined,
): boolean {
  if (!districtName) return true;
  return getParcelDistrictName(parcelId) === districtName;
}

/** 某区县下全部预警演示地块 id */
export function getAlertParcelIdsForDistrict(districtName: string): string[] {
  const ids = HZ_ALERT_PARCELS_BY_DISTRICT[districtName as HzDistrictName];
  return ids ? [...ids] : [];
}

/** 某区县下预警地块对应的 mapFeatureId（osm_id） */
export function getAlertMapFeatureIdsForDistrict(districtName: string): string[] {
  const featureIds: string[] = [];
  for (const parcelId of getAlertParcelIdsForDistrict(districtName)) {
    const fid = getParcelById(parcelId)?.mapFeatureId?.trim();
    if (fid && !featureIds.includes(fid)) featureIds.push(fid);
  }
  return featureIds;
}

const byId = new Map(DEMO_PARCELS.map(p => [p.id, p]));
const byFeature = new Map(
  DEMO_PARCELS.filter(p => p.mapFeatureId).map(p => [p.mapFeatureId!, p]),
);

export function getParcelById(id: string): ParcelLifecycle | undefined {
  return byId.get(id);
}

export function getParcelByMapFeatureId(featureId: string): ParcelLifecycle | undefined {
  const parcelId = MAP_FEATURE_PARCEL_IDS[featureId];
  if (parcelId) return byId.get(parcelId);
  return byFeature.get(featureId);
}

export function normalizeMapFeatureProps(props: unknown): Record<string, unknown> {
  if (!props || typeof props !== 'object') return {};
  return { ...(props as Record<string, unknown>) };
}

export function resolveParcelIdFromFeatureProps(props: Record<string, unknown>): string | undefined {
  const parcelId = props.parcelId;
  if (typeof parcelId === 'string' && parcelId) return parcelId;
  const osmId = props.osm_id != null ? String(props.osm_id) : '';
  if (osmId && MAP_FEATURE_PARCEL_IDS[osmId]) return MAP_FEATURE_PARCEL_IDS[osmId];
  return undefined;
}

