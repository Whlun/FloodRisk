/** 按阶段过滤；未选阶段时返回全部项目 */
export function getProjectsByPhase(phaseKey: PhaseKey | null): ConstructionProject[] {
  if (phaseKey == null) return CONSTRUCTION_PROJECTS;
  return CONSTRUCTION_PROJECTS.filter(p => p.phaseKey === phaseKey);
}

/** 当前阶段右侧看板汇总（与左栏指标一致） */
export function getConstructionSummaryForPhase(phaseKey: PhaseKey) {
  const { count, areaHa } = getPhaseBoardSummary(phaseKey);
  return { totalCount: count, totalAreaHa: areaHa };
}

export function getProjectById(id: string): ConstructionProject | undefined {
  const alertProject = getRegionAlertProjectById(id);
  if (alertProject) return alertProject;
  const direct = CONSTRUCTION_PROJECTS.find(p => p.id === id);
  if (direct) return direct;
  if (id.startsWith('gen-')) {
    const i = Number(id.replace('gen-', '')) || 0;
    const src = CONSTRUCTION_PROJECTS[i % CONSTRUCTION_PROJECTS.length];
    return { ...src, id, name: src.name };
  }
  return undefined;
}

/** 分页 Mock：全量 3002 条演示 */
export function paginateProjects(page: number, pageSize: number, keyword = ''): {
  rows: ConstructionProject[];
  total: number;
} {
  const nk = keyword.trim().toLowerCase();
  const base = Array.from({ length: 48 }, (_, i) => {
    const src = CONSTRUCTION_PROJECTS[i % CONSTRUCTION_PROJECTS.length];
    return {
      ...src,
      id: `gen-${i}`,
      name: i === 0 ? src.name : `${src.name.slice(0, 12)}…（演示${i + 1}）`,
    };
  }).filter(p => !nk || p.name.toLowerCase().includes(nk) || p.region.includes(nk));
  const total = CONSTRUCTION_PROJECT_SUMMARY.totalCount;
  const start = (page - 1) * pageSize;
  return { rows: base.slice(start % base.length, (start % base.length) + pageSize), total };
}
