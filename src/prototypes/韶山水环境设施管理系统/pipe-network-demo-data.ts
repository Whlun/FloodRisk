/** 排水管点台账行（字段与设施管理原型一致） */
export type PipeNodeDemoRow = (typeof pipeNodeData)[number];

/** 排水管线台账行 */
export type PipeLineDemoRow = (typeof pipeLineData)[number];

/** 管线类别码 → 中文（与设施管理列表一致） */
export function formatPipeLineCategory(code: string): string {
  if (code === '1') return '雨水';
  if (code === '2') return '污水';
  if (code === '3') return '合流';
  return '其他';
}

/** 按管点 id 取台账行（与设施管理 `getNodeById` 同源） */
export function getPipeNodeById(nodeId: string): PipeNodeDemoRow | undefined {
  return pipeNodeData.find(n => n.nodeId === nodeId);
}

/** 管点特种：1 = 检查井（GB51187 与设施管理列表一致） */
export const PIPE_NODE_SPECIAL_TYPE_MANHOLE = '1';

/**
 * 接驳点等与台账同源：仅「检查井」管点，用于排水户 `jbdId` 等下拉
 */
export function buildManholePipeNodeSelectOptions(): { value: string; label: string }[] {
  return pipeNodeData
    .filter(n => n.nodeType === PIPE_NODE_SPECIAL_TYPE_MANHOLE)
    .map(n => {
      const mh = 'manholeCategory' in n && n.manholeCategory ? String(n.manholeCategory) : '检查井';
      const road = n.roadName ? ` · ${n.roadName}` : '';
      return {
        value: n.nodeId,
        label: `${n.nodeId}${road} · ${mh}`,
      };
    });
}

