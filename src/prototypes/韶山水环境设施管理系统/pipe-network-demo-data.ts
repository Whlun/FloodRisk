export function formatManholePipeNodeLabel(nodeId: string | undefined): string {
  const id = String(nodeId ?? '').trim();
  if (!id) return '—';
  const n = getPipeNodeById(id);
  if (!n || n.nodeType !== PIPE_NODE_SPECIAL_TYPE_MANHOLE) return id;
  const mh = 'manholeCategory' in n && n.manholeCategory ? String(n.manholeCategory) : '检查井';
  const road = n.roadName ? `${n.roadName} · ` : '';
  return `${id} · ${road}${mh}`;
}

/** 指定管点类型数量（如 `1` 检查井，供综合态势指标卡等） */
export function countPipeNodesByNodeType(nodeType: string): number {
  return pipeNodeData.filter(n => n.nodeType === nodeType).length;
}

/** 按管线类别汇总管长（km） */
export function sumPipeLineKmByCategory(category: '1' | '2'): number {
  let m = 0;
  for (const row of pipeLineData) {
    if (row.lineCategory === category) {
      m += Number(row.lineLength) || 0;
    }
  }
  return m / 1000;
}
