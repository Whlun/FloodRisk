/** 将模板中「每行一条、可带分号/句号」的说明文字转为下拉选项（展示去掉句末「。」） */
function linesToSelectOptions(raw: string): { value: string; label: string }[] {
  return raw
    .split(/\n/)
    .map(l =>
      l
        .trim()
        .replace(/[；;]+$/g, '')
        .replace(/。+$/g, '')
        .trim(),
    )
    .filter(Boolean)
    .map(line => ({ value: line, label: line }));
}

