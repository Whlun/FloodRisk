export function collectRiverOutletTypeLeafValues(nodes: RiverOutletTypeTreeNode[] = RIVER_OUTLET_TYPE_TREE_DATA): string[] {
  const out: string[] = [];
  const walk = (list: RiverOutletTypeTreeNode[]) => {
    for (const n of list) {
      const children = n.children;
      if (children && children.length > 0) {
        walk(children);
      } else {
        const v = n.value ?? n.title;
        if (v != null && String(v).trim() && !String(v).startsWith('__')) {
          out.push(String(v));
        }
      }
    }
  };
  walk(nodes);
  return out;
}

