/** 台账「关联物联监测」为是（`1`）时，地图与详情才可展示物联实时监测口径 */
export function dischargerHasLinkedIotMonitor(r: Pick<PsDischargerRecord, 'linkedIot'>): boolean {
  return String(r.linkedIot ?? '').trim() === '1';
}

export function dischargerLabelYesNo(v: string | undefined): string {
  if (v === '1') return '是';
  if (v === '0') return '否';
  return v && String(v).trim() ? String(v) : '—';
}

export function dischargerLabelDataSource(v: string | undefined): string {
  const hit = DISCHARGER_DATA_SOURCE_OPTIONS.find(o => o.value === String(v ?? '').trim());
  return hit?.label ?? (v ? String(v) : '—');
}
