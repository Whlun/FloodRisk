import { describe, expect, it } from 'vitest';
import {
  generateNextIndicatorCode,
  isAutoGeneratedIndicatorCode,
} from '../src/prototypes/deqing-waterlogging-risk/indicatorCodeGenerator';
import type { Level1Factor } from '../src/prototypes/deqing-waterlogging-risk/types';

describe('indicatorCodeGenerator', () => {
  it('按一级因子递增 U 序号', () => {
    const existing = [{ code: 'HZ_U001' }, { code: 'HZ_U003' }, { code: 'FM_U001' }];
    expect(generateNextIndicatorCode(existing, 'HAZARD')).toBe('HZ_U004');
    expect(generateNextIndicatorCode(existing, 'FORMATION')).toBe('FM_U002');
  });

  it('识别系统自动编码', () => {
    expect(isAutoGeneratedIndicatorCode('HZ_U001')).toBe(true);
    expect(isAutoGeneratedIndicatorCode('FM_LL_COLLECT')).toBe(false);
  });

  it('excludeCode 不参与占用计算（编辑同条指标时）', () => {
    const existing = [{ code: 'BR_U001' }, { code: 'BR_U002' }];
    expect(
      generateNextIndicatorCode(existing, 'BEARING' as Level1Factor, 'BR_U002'),
    ).toBe('BR_U002');
  });
});
